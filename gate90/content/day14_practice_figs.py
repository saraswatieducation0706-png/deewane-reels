os.makedirs(F,exist_ok=True)
def fin(fig,ax,x0,x1,y0,y1,name): ax.set_xlim(x0,x1); ax.set_ylim(y0,y1); save(fig,F+name)
P=lambda x,y,s: np.array([x*s,y*s])
def fourbar(ax,O2,A,B,O4,ps=0.35):
    member(ax,O2,A); member(ax,A,B); member(ax,B,O4)
    pin(ax,*O2,ps); pin(ax,*O4,ps); joint(ax,*A); joint(ax,*B)
def slot_guides(ax,B,y=0.2,back=0.36,fwd=0.9,front=0.8):
    guide(ax,B[0]-front,-y,B[0]+fwd,-y,side=-1); guide(ax,B[0]-back,y,B[0]+fwd,y,side=1)

