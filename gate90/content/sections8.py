# shared T- and I-section drawings (Day 8)
import sys,os; sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","tooling"))
from figlib import *
def tsec_fig(path,bf,tf,tw,hw,s=0.02,unit="mm",na=None):
    W,T,w,h=bf*s,tf*s,tw*s,hw*s; fig,ax=new(2.6,2.6)
    section(ax,[(-W/2,h,W,T),(-w/2,0,w,h)])
    ext(ax,-W/2,h+T+0.05,-W/2,h+T+0.35); ext(ax,W/2,h+T+0.05,W/2,h+T+0.35)
    hdim(ax,-W/2,W/2,h+T+0.3,f"{bf} {unit}")
    ext(ax,W/2+0.05,h,W/2+0.35,h); ext(ax,W/2+0.05,h+T,W/2+0.35,h+T)
    vdim(ax,W/2+0.3,h,h+T,f"{tf}",side="right")
    ext(ax,-w/2-0.05,0,-W/2-0.1,0); vdim(ax,-W/2+0.05,0,h,f"{hw} {unit}",side="left")
    ext(ax,-w/2,-0.05,-w/2,-0.35); ext(ax,w/2,-0.05,w/2,-0.35)
    arrow(ax,-w/2-0.35,-0.3,-w/2,-0.3,lw=0.9); arrow(ax,w/2+0.35,-0.3,w/2,-0.3,lw=0.9); label(ax,w/2+0.4,-0.3,f"{tw}",fs=8,ha="left")
    if na is not None: na_line(ax,-W/2-0.1,W/2+0.1,h+T-na*s)
    ax.set_xlim(-W/2-1.0,W/2+0.9); ax.set_ylim(-0.6,h+T+0.75); save(fig,path)
def isec_fig(path,B,tf,tw,H,s=0.012,unit="mm"):
    W,T,w,Hh=B*s,tf*s,tw*s,H*s; hw=Hh-2*T; fig,ax=new(2.6,2.9)
    section(ax,[(-W/2,0,W,T),(-w/2,T,w,hw),(-W/2,T+hw,W,T)])
    ext(ax,-W/2,Hh+0.05,-W/2,Hh+0.35); ext(ax,W/2,Hh+0.05,W/2,Hh+0.35); hdim(ax,-W/2,W/2,Hh+0.3,f"{B} {unit}")
    ext(ax,W/2+0.05,Hh,W/2+0.35,Hh); ext(ax,W/2+0.05,Hh-T,W/2+0.35,Hh-T)
    arrow(ax,W/2+0.3,Hh+0.3,W/2+0.3,Hh,lw=0.9); arrow(ax,W/2+0.3,Hh-T-0.3,W/2+0.3,Hh-T,lw=0.9); label(ax,W/2+0.38,Hh+0.22,f"{tf}",fs=8,ha="left")
    ext(ax,-W/2-0.05,0,-W/2-0.4,0); ext(ax,-W/2-0.05,Hh,-W/2-0.4,Hh); vdim(ax,-W/2-0.3,0,Hh,f"{H}",side="left")
    yw=T+hw*0.35; arrow(ax,-w/2-0.35,yw,-w/2,yw,lw=0.9); arrow(ax,w/2+0.35,yw,w/2,yw,lw=0.9); label(ax,w/2+0.4,yw,f"{tw}",fs=8,ha="left")
    ax.set_xlim(-W/2-1.0,W/2+0.9); ax.set_ylim(-0.2,Hh+0.7); save(fig,path)
