import sys,os; sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","tooling"))
from figlib import *
F=(sys.argv[1] if len(sys.argv)>1 else "fig")+"/"
os.makedirs(F,exist_ok=True)
def fin(fig,ax,x0,x1,y0,y1,name): ax.set_xlim(x0,x1); ax.set_ylim(y0,y1); save(fig,F+name)
def bolt(ax,x,y,r=0.09): ax.add_patch(Circle((x,y),r,fc="white",ec=K,lw=1.2,zorder=5)); ax.plot([x-r*0.6,x+r*0.6],[y,y],color=K,lw=0.6,zorder=6); ax.plot([x,x],[y-r*0.6,y+r*0.6],color=K,lw=0.6,zorder=6)
def weld_line(ax,x0,y0,x1,y1): ax.plot([x0,x1],[y0,y1],color="#444444",lw=4.5,solid_capstyle="butt",zorder=4)
# P4 plan view of a lap joint: transverse weld across the end + two parallel welds (units 100 mm = 1)
fig,ax=new(3.6,2.0)
ax.add_patch(Rectangle((-0.6,-0.95),2.0,1.9,fc="#f4f4f4",ec=K,lw=1.2))         # lower plate
ax.add_patch(Rectangle((0.0,-0.375),2.6,0.75,fc="#dddddd",ec=K,lw=1.3,zorder=3)) # upper plate, 75 wide
weld_line(ax,0.0,-0.375,0.0,0.375)
weld_line(ax,0.0,0.4,1.4,0.4); weld_line(ax,0.0,-0.4,1.4,-0.4)
arrow(ax,2.6,0,3.3,0); label(ax,3.35,0.12,"200 kN",fs=8,ha="left",va="bottom")
arrow(ax,-0.6,0,-1.2,0)
hdim(ax,0,1.4,1.15,"l (each)",above=True,fs=8); ext(ax,0,0.45,0,1.25); ext(ax,1.4,0.45,1.4,1.25)
vdim(ax,2.3,-0.375,0.375,"75",side="left",fs=8)
label(ax,-0.75,-1.25,"transverse weld",fs=7,ha="center"); arrow(ax,-0.6,-1.15,-0.04,-0.2,lw=0.7)
label(ax,1.0,-1.25,"parallel welds",fs=7); arrow(ax,1.0,-1.15,0.9,-0.45,lw=0.7)
fin(fig,ax,-1.4,4.0,-1.4,1.55,"d25p_q4.png")
# P6 front view: bracket plate on a column flange, two horizontal fillet welds 100 long and 120 apart; 15 kN at 150 from the weld centroid
fig,ax=new(3.4,2.3)
ax.add_patch(Rectangle((0,-1.0),1.0,2.0,fc="#f4f4f4",ec=K,lw=1.0))
ax.add_patch(Polygon([[0,-0.6],[0,0.6],[2.2,0.6],[2.2,0.2],[1.0,-0.6]],closed=True,fc="#dddddd",ec=K,lw=1.3,zorder=3))
weld_line(ax,0,0.62,1.0,0.62); weld_line(ax,0,-0.62,1.0,-0.62)
ax.plot([0.5,0.5],[-0.85,0.85],color=K,lw=0.5,ls="-.",zorder=5); joint(ax,0.5,0,0.04)
arrow(ax,2.0,1.4,2.0,0.62); label(ax,2.1,1.3,"15 kN",fs=8,ha="left")
hdim(ax,0.5,2.0,1.05,"150",above=True,fs=8); ext(ax,0.5,0.85,0.5,1.15); ext(ax,2.0,0.95,2.0,1.15)
hdim(ax,0,1.0,-1.25,"100",above=False,fs=8); ext(ax,0,-1.0,0,-1.35); ext(ax,1.0,-1.0,1.0,-1.35)
vdim(ax,-0.35,-0.62,0.62,"120",side="left",fs=8); ext(ax,-0.02,0.62,-0.45,0.62); ext(ax,-0.02,-0.62,-0.45,-0.62)
label(ax,-0.08,-0.9,"column flange",fs=7,ha="right"); label(ax,1.6,-0.35,"G = weld centroid",fs=6.5,ha="left")
label(ax,0.62,0.08,"G",fs=7,ha="left")
fin(fig,ax,-1.1,3.0,-1.65,1.75,"d25p_q6.png")
# P10 three bolts in a vertical line, pitch 80, load 12 kN at 250 from the middle bolt
fig,ax=new(3.3,2.3)
ax.add_patch(Polygon([[-0.4,-1.15],[-0.4,1.15],[3.05,1.15],[3.05,0.75],[0.4,-1.15]],closed=True,fc="#eeeeee",ec=K,lw=1.3))
for y in (-0.8,0,0.8): bolt(ax,0,y)
arrow(ax,2.5,1.9,2.5,1.17); label(ax,2.6,1.8,"12 kN",fs=8,ha="left")
hdim(ax,0,2.5,1.5,"250",above=True,fs=8); ext(ax,0,1.0,0,1.6); ext(ax,2.5,1.2,2.5,1.6)
vdim(ax,-0.75,0,0.8,"80",side="left",fs=8); vdim(ax,-0.75,-0.8,0,"80",side="left",fs=8)
for y in (-0.8,0,0.8): ext(ax,-0.12,y,-0.85,y)
label(ax,1.6,-1.3,"dimensions in mm",fs=7)
fin(fig,ax,-1.4,3.5,-1.5,2.1,"d25p_q10.png")
# P11 side view of a bracket bolted to a wall: bolts at 40 and 240 from the tilting edge, 30 kN at 200
fig,ax=new(3.3,2.6)
hatch_wall(ax,0,-0.3,3.0,left=True,size=0.15)
ax.add_patch(Polygon([[0,0],[0,2.8],[0.25,2.8],[0.25,0.25],[2.3,0.25],[2.3,0]],closed=True,fc="#eeeeee",ec=K,lw=1.3))
for y in (0.4,2.4):
    ax.add_patch(Rectangle((-0.35,y-0.07),0.75,0.14,fc="#999999",ec=K,lw=0.9,zorder=5))
arrow(ax,2.0,1.3,2.0,0.28); label(ax,2.1,1.2,"30 kN",fs=8,ha="left")
hdim(ax,0,2.0,-0.55,"200",above=False,fs=8); ext(ax,2.0,0,2.0,-0.6)
vdim(ax,0.75,0,0.4,"",fs=8); label(ax,0.85,0.62,"40",fs=8,ha="left"); ext(ax,0.42,0.4,0.85,0.4)
vdim(ax,1.3,0,2.4,"240",side="right",fs=8); ext(ax,0.42,2.4,1.4,2.4)
ext(ax,0.27,0.0,1.4,0.0)
arrow(ax,0.9,-1.1,0.05,-0.05,lw=0.8); label(ax,0.95,-1.15,"tilting edge",fs=7,ha="left")
label(ax,1.6,2.62,"2 bolts in each row",fs=7)
fin(fig,ax,-0.6,3.2,-1.4,3.1,"d25p_q11.png")
