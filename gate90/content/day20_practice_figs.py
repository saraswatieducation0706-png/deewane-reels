import sys,os; sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","tooling"))
from figlib import *
F=(sys.argv[1] if len(sys.argv)>1 else "fig")+"/"
os.makedirs(F,exist_ok=True)
def fin(fig,ax,x0,x1,y0,y1,name): ax.set_xlim(x0,x1); ax.set_ylim(y0,y1); save(fig,F+name)
# P1 mass held between two vertical springs (top fixed, bottom fixed)
fig,ax=new(1.9,2.9)
hatch_ground(ax,-0.6,0.6,2.2,down=False,size=0.15); hatch_ground(ax,-0.6,0.6,-2.2,down=True,size=0.15)
spring(ax,(0,2.2),(0,0.35),n=5,w=0.14); spring(ax,(0,-0.35),(0,-2.2),n=5,w=0.14)
block(ax,0,0,0.9,0.7,"4 kg",fs=9)
label(ax,0.28,1.27,"k₁ = 2000 N/m",fs=8,ha="left"); label(ax,0.28,-1.27,"k₂ = 3000 N/m",fs=8,ha="left")
fin(fig,ax,-0.8,2.3,-2.5,2.5,"d20p_q1.png")
# P7 inverted pendulum: bar hinged at the bottom, two horizontal springs at the top
fig,ax=new(2.6,2.7)
pin(ax,0,0,0.35); member(ax,(0,0),(0,2.0),lw=4); joint(ax,0,0,0.06)
hatch_wall(ax,-1.4,1.7,2.3,left=True,size=0.14); hatch_wall(ax,1.4,1.7,2.3,left=False,size=0.14)
spring(ax,(-1.4,2.0),(-0.05,2.0),n=4,w=0.11); spring(ax,(0.05,2.0),(1.4,2.0),n=4,w=0.11)
label(ax,-0.72,2.3,"k",fs=9); label(ax,0.72,2.3,"k",fs=9)
vdim(ax,-1.75,0,2.0,"L = 1 m",side="left",fs=8); ext(ax,-0.2,0,-1.85,0); ext(ax,-1.45,2.0,-1.85,2.0)
label(ax,0.2,1.0,"m = 2 kg",fs=8,ha="left")
fin(fig,ax,-2.7,1.9,-0.45,2.6,"d20p_q7.png")
# P13 mass on a rope over a pulley (solid disc), other rope end tied to a spring fixed to the ground
fig,ax=new(2.6,2.9)
r=0.5; ax.add_patch(Circle((0,2.0),r,fc="#dddddd",ec=K,lw=1.3)); joint(ax,0,2.0,0.06)
ax.plot([0,0],[2.0,2.9],color=K,lw=1.6); hatch_ground(ax,-0.5,0.5,2.9,down=False,size=0.14)
ax.plot([r,r],[2.0,0.9],color=K,lw=1.2); block(ax,r,0.6,0.6,0.6,"m",fs=9)
ax.plot([-r,-r],[2.0,1.3],color=K,lw=1.2); spring(ax,(-r,1.3),(-r,-0.3),n=4,w=0.12)
hatch_ground(ax,-r-0.4,-r+0.4,-0.3,down=True,size=0.14)
label(ax,-r-0.22,0.5,"k",fs=9,ha="right"); label(ax,0.62,2.55,"M, r",fs=8,ha="left")
fin(fig,ax,-1.5,1.6,-0.55,3.1,"d20p_q13.png")
