ax.plot([c,c],[0,R],color=K,lw=0.6,ls=":"); label(ax,c+3,R+5,"τmax = R = 50",fs=7,ha="left")
ax.set_xlim(-80,105); ax.set_ylim(-68,68); save(fig,F+"d5p_s6.png")
# P8 steel rod inside copper tube (heated)
