import sys,os; sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","tooling"))
from figlib import *
F=sys.argv[1] if len(sys.argv)>1 else "fig/"
# P2 stepped bar
fig,ax=new(3.6,1.5)
hatch_wall(ax,0,-0.6,0.6,left=True)
ax.add_patch(Rectangle((0,-0.3),2.4,0.6,fc="#dddddd",ec=K,lw=1.3)); ax.add_patch(Rectangle((2.4,-0.2),1.8,0.4,fc="#dddddd",ec=K,lw=1.3))
arrow(ax,4.2,0,5.0,0); label(ax,4.65,0.25,"50 kN",fs=8)
label(ax,1.2,0,"d = 30 mm",fs=8); label(ax,3.3,0,"d = 20 mm",fs=8)
dim(ax,0,-0.6,2.4,-0.6,"400 mm",off=(0,-0.2)); dim(ax,2.4,-0.6,4.2,-0.6,"300 mm",off=(0,-0.2))
ax.plot([2.4,2.4],[-0.3,-0.7],color=K,lw=0.5,ls=":"); ax.plot([4.2,4.2],[-0.2,-0.7],color=K,lw=0.5,ls=":")
ax.set_xlim(-0.4,5.2); ax.set_ylim(-1.1,0.8); save(fig,F+"d5p_q2.png")
# P6 stress element
fig,ax=new(2.8,2.8); stress_element(ax,-30,50,-30,a=1.4)
